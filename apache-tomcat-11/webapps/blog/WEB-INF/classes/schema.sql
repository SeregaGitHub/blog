-- update post
CREATE OR REPLACE PROCEDURE update_post(IN update_post_id INTEGER, IN post_name varchar, IN post_image_url varchar, IN post_description text[], IN tags_array varchar[])
LANGUAGE plpgsql
AS
'
DECLARE
  tags_id_arr int[];
BEGIN
	UPDATE post
	SET
	name = post_name,
	image_url = post_image_url,
	description = post_description
	WHERE id = update_post_id;

	INSERT INTO tag(name)
	VALUES (unnest(tags_array))
	ON CONFLICT DO NOTHING;

	SELECT ARRAY_AGG(t.id) FROM tag t WHERE name LIKE ANY(tags_array) INTO tags_id_arr;

	DELETE FROM post_tag
	WHERE post_id = update_post_id
	AND tag_id <> ANY(tags_id_arr);

	INSERT INTO post_tag
	VALUES
	(update_post_id, unnest(tags_id_arr))
	ON CONFLICT DO NOTHING;
END;'
;

