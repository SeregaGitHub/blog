CREATE TABLE IF NOT EXISTS post (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  name varchar(64) NOT NULL,
  image_url varchar(512) NOT NULL,
  description text[] NOT NULL,
  commentsCount INTEGER DEFAULT 0,
  CONSTRAINT pk_post_id PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS tag (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  name varchar(64) NOT NULL,
  CONSTRAINT pk_tag_id PRIMARY KEY (id),
  CONSTRAINT uk_tag_name UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS post_tag (
	post_id INTEGER,
	tag_id INTEGER,
	CONSTRAINT pk_post_tag_id PRIMARY KEY (post_id, tag_id),
	CONSTRAINT fk_post_tag_post_id FOREIGN KEY (post_id)
          REFERENCES post (id) ON DELETE CASCADE,
	CONSTRAINT fk_post_tag_tag_id FOREIGN KEY (tag_id)
          REFERENCES tag (id) --ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS likes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  count INTEGER NOT NULL,
  post_id INTEGER NOT NULL,
  CONSTRAINT pk_likes_id PRIMARY KEY (id),
  CONSTRAINT uk_likes_post_id UNIQUE (post_id),
  CONSTRAINT fk_likes_post_id FOREIGN KEY (post_id)
          REFERENCES post (id) ON DELETE CASCADE
); -- create index post_id, count ??? - UNIQUE (post_id) exists

CREATE TABLE IF NOT EXISTS comment (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  post_comment varchar(2048),
  post_id INTEGER NOT NULL,
  CONSTRAINT pk_comment_id PRIMARY KEY (id),
  CONSTRAINT fk_comment_post_id FOREIGN KEY (post_id)
          REFERENCES post (id) ON DELETE CASCADE
);

